-- Vigencia obligatoria desde el 30 de octubre de 2026 para esquema `public`.
-- ==============================================================================
-- Regla de Gobernanza:
-- Ninguna tabla creada en `public` recibe permisos automáticos para PostgREST /
-- GraphQL / supabase-js. Toda nueva tabla DEBE incluir en su migración:
--   1. Habilitación obligatoria de Row Level Security (RLS).
--   2. Políticas estrictas `auth.uid() = user_id` (para datos de usuario).
--   3. Sentencias explícitas de `GRANT` a `anon`, `authenticated` y `service_role`.
-- ==============================================================================

GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

-- 1. Tablas de catálogo de lectura pública (bajo políticas RLS SELECT)
GRANT SELECT ON TABLE
    public.careers,
    public.courses,
    public.course_books,
    public.course_careers,
    public.course_topics,
    public.resources,
    public.topics,
    public.topic_resources,
    public.decks,
    public.web_traffic
TO anon;

-- 2. Tablas operativas de usuario autenticado (protegidas por RLS auth.uid() = user_id / id)
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
    public.careers,
    public.courses,
    public.course_books,
    public.course_careers,
    public.course_topics,
    public.resources,
    public.topics,
    public.topic_resources,
    public.decks,
    public.page_views,
    public.quiz_history,
    public.search_history,
    public.user_book_library,
    public.user_course_library,
    public.user_flashcards,
    public.user_notes,
    public.user_question_history,
    public.user_simulator_preferences,
    public.users,
    public.web_traffic
TO authenticated;

-- 3. Rol administrativo de backend (service_role)
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated, service_role;

-- 4. Aislamiento estricto de tablas sensibles de servidor (claves de respuesta y pagos)
REVOKE ALL ON TABLE
    public.question_bank,
    public.case_scenarios,
    public.payment_events,
    public.quiz_sessions,
    public.quiz_session_questions
FROM PUBLIC, anon, authenticated;

